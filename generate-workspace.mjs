#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const markerName = '.resolver-cache-benchmark-fixture'
const blueprint = readBlueprint()
const productRoots = [
  ...new Set(
    blueprint.packages
      .map((pkg) => pkg.path.split('/')[0])
      .filter((segment) => segment !== '.'),
  ),
].sort()
const managedEntries = [
  ...productRoots,
  'package.json',
  '.npmrc',
  '.yarnrc.yml',
  'pnpm-workspace.yaml',
  'fixture-metadata.json',
  'pnpm-lock.yaml',
  'yarn.lock',
  '.yarn',
  '.pnp.cjs',
  '.pnp.loader.mjs',
  'node_modules',
  '.pnpm-store',
]

resetGeneratedWorkspace()
generateWorkspace()

function readBlueprint() {
  const value = JSON.parse(readFileSync(join(root, 'blueprint.json'), 'utf8'))
  const withoutHash = { ...value }
  delete withoutHash.sha256
  const actualHash = digest(JSON.stringify(withoutHash))
  if (actualHash !== value.sha256) {
    throw new Error(`blueprint SHA-256 mismatch: ${actualHash} != ${value.sha256}`)
  }
  return value
}

function resetGeneratedWorkspace() {
  const marker = join(root, markerName)
  if (!existsSync(marker)) {
    const collisions = managedEntries.filter((entry) => existsSync(join(root, entry)))
    if (collisions.length > 0) {
      throw new Error(
        `Refusing to overwrite an unmarked directory; already present: ${collisions.join(', ')}`,
      )
    }
  }
  for (const entry of managedEntries) {
    rmSync(join(root, entry), { recursive: true, force: true })
  }
  writeFileSync(marker, 'Generated by generate-workspace.mjs.\n')
}

function generateWorkspace() {
  const names = new Set(blueprint.packages.map((pkg) => pkg.name))
  const incoming = new Map([...names].map((name) => [name, 0]))

  for (const pkg of blueprint.packages) {
    const dependencies = Object.fromEntries(
      pkg.dependencies.map((name) => {
        if (!names.has(name)) throw new Error(`unknown workspace dependency: ${name}`)
        incoming.set(name, incoming.get(name) + 1)
        return [name, 'workspace:*']
      }),
    )
    const manifest = {
      name: pkg.name,
      version: '1.0.0',
      private: true,
      ...(pkg.path === '.'
        ? {
            packageManager: 'yarn@4.18.0',
            workspaces: blueprint.patterns.filter((pattern) => pattern !== '.'),
          }
        : {}),
      ...(pkg.dependencies.length === 0 ? {} : { dependencies }),
    }
    const directory = pkg.path === '.' ? root : join(root, pkg.path)
    mkdirSync(directory, { recursive: true })
    writeJson(join(directory, 'package.json'), manifest)
  }

  writeFileSync(
    join(root, 'pnpm-workspace.yaml'),
    [
      'packages:',
      ...blueprint.patterns.map((pattern) => `  - '${pattern}'`),
      'storeDir: .pnpm-store',
      'enableGlobalVirtualStore: false',
      'pmOnFail: ignore',
      '',
    ].join('\n'),
  )
  writeFileSync(
    join(root, '.npmrc'),
    ['auto-install-peers=false', 'dedupe-peer-dependents=false', 'ignore-scripts=true', ''].join(
      '\n',
    ),
  )
  writeFileSync(
    join(root, '.yarnrc.yml'),
    [
      'enableNetwork: false',
      'enableTelemetry: false',
      'enableTimers: true',
      'ignorePath: true',
      '',
    ].join('\n'),
  )

  const topSharedPackages = [...incoming]
    .map(([name, consumers]) => ({ name, consumers }))
    .sort((left, right) => right.consumers - left.consumers || left.name.localeCompare(right.name))
    .slice(0, 20)
  writeJson(join(root, 'fixture-metadata.json'), {
    blueprintSha256: blueprint.sha256,
    workspaceCount: blueprint.packages.length,
    workspacePatterns: blueprint.patterns.length,
    dependencyEdges: blueprint.packages.reduce(
      (total, pkg) => total + pkg.dependencies.length,
      0,
    ),
    topSharedPackages,
  })

  console.log(
    `Generated ${blueprint.packages.length.toLocaleString()} workspaces with ` +
      `${blueprint.stats.dependencyEdges.toLocaleString()} shared workspace edges in ${root}.`,
  )
  console.log('Run either package manager directly from this directory:')
  console.log('  yarn install --mode update-lockfile')
  console.log(
    '  pnpm install --lockfile-only --trust-lockfile --offline --ignore-scripts',
  )
}

function writeJson(path, value) {
  writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`)
}

function digest(value) {
  return createHash('sha256').update(value).digest('hex')
}
